// Embeds drizzle-kit's SQL migrations into a TypeScript module so the bundled
// Electron main process carries them (no loose files in the asar).
// Run via `pnpm --filter @cmp/database db:generate`. A unit test fails if
// src/migrations.generated.ts drifts from ./migrations.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const journal = JSON.parse(
  readFileSync(join(root, "migrations/meta/_journal.json"), "utf8"),
);

const migrations = journal.entries.map((entry) => ({
  tag: entry.tag,
  sql: readFileSync(join(root, "migrations", `${entry.tag}.sql`), "utf8"),
}));

const source = `// GENERATED by scripts/embed-migrations.mjs — do not edit.
// Source: packages/database/migrations (drizzle-kit generate).
import type { Migration } from "./migrate";

export const migrations: readonly Migration[] = ${JSON.stringify(migrations, null, 2)};
`;

writeFileSync(join(root, "src/migrations.generated.ts"), source);
console.log(`Embedded ${migrations.length} migration(s).`);
